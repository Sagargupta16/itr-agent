// Runs every case in scripts/validation-cases.json through the BUILT server
// (dist/index.js over stdio, the same artifact `npx itr-agent` starts) and
// compares each figure against its published or hand-worked source.
//
//   node scripts/validate.mjs           check: exit 1 on any mismatch, or if
//                                       docs/validation.md is out of date
//   node scripts/validate.mjs --write   regenerate docs/validation.md
//
// Run `pnpm build` first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docPath = join(root, "docs", "validation.md");
const { sources, cases } = JSON.parse(
  readFileSync(join(root, "scripts", "validation-cases.json"), "utf8"),
);

const transport = new StdioClientTransport({
  command: process.execPath,
  args: [join(root, "dist", "index.js")],
  stderr: "ignore",
});
const client = new Client({ name: "itr-agent-validate", version: "0" });
await client.connect(transport);

const inr = new Intl.NumberFormat("en-IN");
const fmt = (v) => (typeof v === "number" ? inr.format(v) : String(v));

let rulePackVersion = "unknown";
let checks = 0;
let failures = 0;
const rows = { "budget-speech": [], statute: [] };

for (const c of cases) {
  const res = await client.callTool({ name: c.tool, arguments: c.args });
  const out = res.structuredContent;
  if (res.isError || !out) {
    throw new Error(`${c.id}: ${c.tool} returned an error`);
  }
  rulePackVersion = out.rulePackVersion ?? rulePackVersion;
  const cells = [];
  let ok = true;
  for (const [field, expected] of Object.entries(c.expect)) {
    checks += 1;
    const actual = out[field];
    const match = actual === expected;
    if (!match) {
      ok = false;
      failures += 1;
      console.error(
        `FAIL ${c.id}.${field}: expected ${expected}, got ${actual}`,
      );
    }
    cells.push(
      `${field} ${fmt(expected)}${match ? "" : ` (engine ${fmt(actual)})`}`,
    );
  }
  rows[c.source].push({ c, cells, ok });
}
await client.close();

const args = (a) =>
  Object.entries(a)
    .map(([k, v]) => `${k}=${fmt(v)}`)
    .join(", ");

const lines = [
  "# Validation",
  "",
  "<!-- Generated by scripts/validate.mjs from scripts/validation-cases.json. Do not edit by hand: change the cases and run `pnpm validate --write`. -->",
  "",
  `Every figure below was produced by the built server (\`dist/index.js\`, rule pack ${rulePackVersion}) over stdio, the same way an MCP client calls it, and compared against the source figure. ${cases.length} cases, ${checks} figures, ${checks - failures} match.`,
  "",
  "CI runs `pnpm validate` on every push, so this table cannot drift from the engine: a changed figure fails the build until the case or the engine is fixed.",
  "",
];

const section = (key, heading, withWorking) => {
  const src = sources[key];
  lines.push(`## ${heading}`, "");
  lines.push(`Source: [${src.title}](${src.url}). ${src.note}`, "");
  lines.push(
    withWorking
      ? "| Case | Inputs | Working | Figures checked | Match |"
      : "| Case | Inputs | Figures checked | Match |",
    withWorking
      ? "| --- | --- | --- | --- | --- |"
      : "| --- | --- | --- | --- |",
  );
  for (const { c, cells, ok } of rows[key]) {
    const parts = [c.label, `\`${c.tool}\` ${args(c.args)}`];
    if (withWorking) parts.push(c.working ?? "");
    parts.push(cells.join("<br>"), ok ? "yes" : "**NO**");
    lines.push(`| ${parts.join(" | ")} |`);
  }
  lines.push("");
};

section("budget-speech", "Published by the Ministry of Finance", false);
section("statute", "Worked by hand from the statute", true);

lines.push(
  "## What this does not cover",
  "",
  "- The official Income and Tax Calculator on the e-Filing portal cannot be driven by a script (it answered an automated browser with `Permission Denied!!` on 2026-10-18), so no row here is a calculator screenshot. Comparing a filed return's computation against `compute_tax` is the next step, and a row from a CA-prepared return is welcome as a pull request.",
  "- Old-regime deductions, HRA, 234A/B/C interest and the parsers are pinned by the unit tests in `tests/`, not by this table.",
  "",
);

const doc = lines.join("\n");
if (process.argv.includes("--write")) {
  writeFileSync(docPath, doc);
  console.log(
    `wrote docs/validation.md (${checks - failures}/${checks} match)`,
  );
} else {
  let current = "";
  try {
    current = readFileSync(docPath, "utf8");
  } catch {}
  console.log(`${checks - failures}/${checks} figures match`);
  if (current !== doc) {
    console.error(
      "docs/validation.md is out of date: run `pnpm validate --write`",
    );
    process.exit(1);
  }
}
process.exit(failures === 0 ? 0 : 1);
